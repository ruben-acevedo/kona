const { contextBridge, ipcRenderer } = require('electron');

const CHANNELS = ['win:state', 'win:shown', 'tab:open', 'shortcut', 'ext:confirm', 'ext:changed', 'page:mousedown',
  'perm:ask', 'download:start', 'download:done', 'update:ready', 'tab:external', 'download:progress', 'ctx:page',
  'browserAction.update', 'ext:tab-create', 'ext:tab-select', 'ext:tab-remove',
  'pw:suggest', 'pw:suggest-hide', 'pw:offer-save', 'pw:saved', 'pw:changed', 'tab:audio', 'reader:state', 'popup:blocked', 'site:jsblocked', 'apps:changed', 'app:navigate',
  'share:pick', 'share:sources', 'share:started', 'share:ended', 'tab:adopt', 'win:promote', 'media:list',
  'session:restore-tabs', 'tab:crashed', 'tab:responsive',
  'af:suggest', 'af:suggest-hide', 'af:offer-save', 'af:changed', 'tab:select'];

contextBridge.exposeInMainWorld('kona', {
  platform: process.platform,
  close: () => ipcRenderer.send('win:close'),
  minimize: () => ipcRenderer.send('win:minimize'),
  maximize: () => ipcRenderer.send('win:maximize'),
  devtools: () => ipcRenderer.send('win:devtools'),
  toggleFullscreen: () => ipcRenderer.send('win:fullscreen'),
  // várias janelas
  newWindow: (url) => ipcRenderer.invoke('win:new', url),
  windowCount: () => ipcRenderer.invoke('win:count'),
  windowRole: () => ipcRenderer.invoke('win:role'),
  otherWindows: () => ipcRenderer.invoke('win:others'),
  tabMove: (data) => ipcRenderer.invoke('tab:move', data),
  otherTabs: () => ipcRenderer.invoke('win:tabs'),
  focusTab: (winId, tabId) => ipcRenderer.invoke('win:focus-tab', winId, tabId),
  windowPrivate: (on) => ipcRenderer.send('win:private', !!on),
  tabPinned: (wcId, on) => ipcRenderer.send('tab:pinned', wcId, !!on),
  setLanguage: (lang) => ipcRenderer.send('lang:set', lang),
  sessionUpdate: (snap) => ipcRenderer.send('session:update', snap),
  // endereços e cartões (o número do cartão nunca chega à interface)
  af: {
    setPrefs: (p) => ipcRenderer.invoke('af:set-prefs', p),
    fill: (suggestId, itemId) => ipcRenderer.invoke('af:fill', suggestId, itemId),
    answer: (id, answer) => ipcRenderer.invoke('af:save-answer', id, answer),
    list: () => ipcRenderer.invoke('af:list'),
    saveAddress: (data, id) => ipcRenderer.invoke('af:save-address', data, id),
    saveCard: (data, id) => ipcRenderer.invoke('af:save-card', data, id),
    remove: (kind, id) => ipcRenderer.invoke('af:delete', kind, id),
    importAddresses: (list) => ipcRenderer.invoke('import:addresses', list),
  },
  sessionRecovery: () => ipcRenderer.invoke('session:recovery'),
  sessionRestore: () => ipcRenderer.invoke('session:restore'),
  sessionDismiss: () => ipcRenderer.invoke('session:dismiss'),
  tabKill: (wcId) => ipcRenderer.invoke('tab:kill', wcId),
  mediaList: () => ipcRenderer.invoke('media:list'),
  mediaControl: (wcId, action) => ipcRenderer.send('media:control', wcId, action),
  apps: {
    inspect: (wcId) => ipcRenderer.invoke('app:inspect', wcId),
    check: (wcId, partition) => ipcRenderer.invoke('app:check', wcId, partition),
    install: (req) => ipcRenderer.invoke('app:install', req),
    list: () => ipcRenderer.invoke('app:list'),
    get: (id) => ipcRenderer.invoke('app:get', id),
    open: (id, url) => ipcRenderer.invoke('app:open', id, url),
    uninstall: (id) => ipcRenderer.invoke('app:uninstall', id),
    toBrowser: (url) => ipcRenderer.send('app:browser', url),
  },
  siteInfo: (partition, url) => ipcRenderer.invoke('site:info', partition, url),
  siteKey: (url) => ipcRenderer.invoke('site:key', url),
  setPrivateSiteRules: (partition, rules) => ipcRenderer.send('siterules:private', partition, rules),
  shareChoice: (id, choice) => ipcRenderer.send('share:choice', id, choice),
  shareStop: (id) => ipcRenderer.send('share:stop', id),
  reader: {
    open: (id, s) => ipcRenderer.invoke('reader:open', id, s),
    close: (id) => ipcRenderer.invoke('reader:close', id),
    apply: (id, s) => ipcRenderer.invoke('reader:apply', id, s),
    speech: (id, cmd) => ipcRenderer.invoke('reader:speech', id, cmd),
  },
  setTheme: (value) => ipcRenderer.send('theme:set', value),
  extList: () => ipcRenderer.invoke('ext:list'),
  extRemove: (id) => ipcRenderer.invoke('ext:remove', id),
  extConfirmReply: (id, ok) => ipcRenderer.send('ext:confirm-reply', { id, ok }),
  suggest: (q, partition, engine) => ipcRenderer.invoke('suggest', q, partition, engine),
  setPrefs: (partition, prefs) => ipcRenderer.send('prefs:set', partition, prefs),
  permReply: (id, allow) => ipcRenderer.send('perm:reply', { id, allow }),
  showDownload: (file) => ipcRenderer.invoke('download:show', file),
  ctxDo: (id, act, data) => ipcRenderer.invoke('ctx:do', id, act, data),
  // senhas (o processo principal confere origem e Windows Hello; a interface nunca guarda senhas)
  pw: {
    setOffer: (on) => ipcRenderer.invoke('pw:set-offer', on),
    fill: (suggestId, accountId, generated) => ipcRenderer.invoke('pw:fill', suggestId, accountId, generated),
    neverHere: (suggestId) => ipcRenderer.invoke('pw:never-here', suggestId),
    answer: (id, answer, username) => ipcRenderer.invoke('pw:save-answer', id, answer, username),
    list: () => ipcRenderer.invoke('pw:list'),
    reveal: (id) => ipcRenderer.invoke('pw:reveal', id),
    copy: (id) => ipcRenderer.invoke('pw:copy', id),
    edit: (id, data) => ipcRenderer.invoke('pw:edit', id, data),
    remove: (id) => ipcRenderer.invoke('pw:delete', id),
    neverRemove: (origin) => ipcRenderer.invoke('pw:never-remove', origin),
    importCsv: () => ipcRenderer.invoke('pw:import'),
    exportCsv: () => ipcRenderer.invoke('pw:export'),
  },
  // extensões: estado dos botões (ícone, contador, título), abrir popup, abas pedidas por extensões
  extActionState: (partition) => ipcRenderer.invoke('crx-msg-remote', partition, 'browserAction.getState'),
  extActionActivate: (partition, details) => ipcRenderer.invoke('crx-msg-remote', partition, 'browserAction.activate', details),
  extActionObserve: (partition) => ipcRenderer.invoke('crx-msg-remote', partition, 'browserAction.addObserver'),
  extTabCreated: (id, wcId) => ipcRenderer.send('ext:tab-created', id, wcId),
  extTabSelected: (wcId) => ipcRenderer.invoke('ext:tab-selected', wcId),
  extMenuClick: (id) => ipcRenderer.invoke('ext:menu-click', id),
  ctxUi: (act) => ipcRenderer.invoke('ctx:ui', act),
  clipboardRead: () => ipcRenderer.invoke('clipboard:read'),
  clipboardWrite: (text) => ipcRenderer.send('clipboard:write', text),
  downloadPause: (id) => ipcRenderer.invoke('download:pause', id),
  downloadResume: (id) => ipcRenderer.invoke('download:resume', id),
  downloadCancel: (id) => ipcRenderer.invoke('download:cancel', id),
  downloadKeep: (id) => ipcRenderer.invoke('download:keep', id),
  downloadDiscard: (id) => ipcRenderer.invoke('download:discard', id),
  downloadRetry: (url) => ipcRenderer.invoke('download:retry', url),
  downloadOpen: (file) => ipcRenderer.invoke('download:open', file),
  downloadExists: (files) => ipcRenderer.invoke('download:exists', files),
  downloadIcon: (file) => ipcRenderer.invoke('download:icon', file),
  downloadDrag: (file) => ipcRenderer.send('download:drag', file),
  pickFolder: () => ipcRenderer.invoke('dialog:folder'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  sitesList: (partition) => ipcRenderer.invoke('sites:list', partition),
  sitesRemove: (partition, site) => ipcRenderer.invoke('sites:remove', partition, site),
  privateOpen: () => ipcRenderer.invoke('private:open'),
  clearBrowsingData: (partition, what) => ipcRenderer.invoke('data:clear', partition, what),
  installUpdate: () => ipcRenderer.send('update:install'),
  privateClose: (partition) => ipcRenderer.invoke('private:close', partition),
  profileUse: (partition) => ipcRenderer.invoke('profile:use', partition),
  profileForget: (partition) => ipcRenderer.invoke('profile:forget', partition),
  defaultStatus: () => ipcRenderer.invoke('default:status'),
  defaultSet: () => ipcRenderer.invoke('default:set'),
  importSources: () => ipcRenderer.invoke('import:sources'),
  importRead: (id) => ipcRenderer.invoke('import:read', id),
  importExtension: (id) => ipcRenderer.invoke('import:extension', id),
  on: (channel, fn) => {
    if (!CHANNELS.includes(channel)) return;
    ipcRenderer.on(channel, (_e, ...args) => fn(...args));
  },
});
